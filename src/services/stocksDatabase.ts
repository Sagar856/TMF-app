/**
 * Searches the stock catalog for matching symbols, company names, or aliases.
 */
export function searchStocksCatalog(query: string, sectorFilter?: string): StockItem[] {
  const clean = query.trim().toLowerCase();
  
  return POPULAR_STOCKS_CATALOG.filter((stock) => {
    if (sectorFilter && sectorFilter !== 'All' && stock.sector !== sectorFilter) {
      return false;
    }
    if (!clean) return true;

    const matchSymbol = stock.symbol.toLowerCase().includes(clean);
    const matchName = stock.name.toLowerCase().includes(clean);
    const matchAlias = stock.aliases?.some((a) => a.toLowerCase().includes(clean));
    const matchSector = stock.sector.toLowerCase().includes(clean);

    return matchSymbol || matchName || matchAlias || matchSector;
  });
}

/**
 * Finds a stock by exact symbol, alias, or closest match.
 */
export function findStockBySymbol(query: string): StockItem | undefined {
  const clean = query.trim().toUpperCase().replace('.NS', '').replace('.BO', '');
  if (!clean) return undefined;

  // Exact symbol match
  const exact = POPULAR_STOCKS_CATALOG.find((s) => s.symbol === clean);
  if (exact) return exact;

  // Exact alias match
  const aliasMatch = POPULAR_STOCKS_CATALOG.find((s) =>
    s.aliases?.some((a) => a.toUpperCase() === clean)
  );
  if (aliasMatch) return aliasMatch;

  // Partial match
  return POPULAR_STOCKS_CATALOG.find(
    (s) => s.symbol.includes(clean) || s.name.toUpperCase().includes(clean)
  );
}
